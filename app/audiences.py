"""Аудитория — первоклассная сущность, а не флаг «соцконтракт или нет».

Одна и та же идея приходит к нам с разных сторон, и мерить их одной линейкой
— прямой путь к ощущению «отчёт не стоил денег» (принцип 4). Поэтому `purpose`
протянут через весь продукт: проверку спроса, оптику платного разбора, воронку
владельца, цели Метрики.

Но ОПИСАНА аудитория была четырьмя разными способами в четырёх файлах:
персона и критерий балла в `report_engine`, переопределения разделов через
ключ `"social"` внутри `SECTION_SPECS`, ветка `IS_SOCIAL_CONTRACT` в скрипте
страницы результата и русская метка прямо в `desk.html`. На двух аудиториях
это ещё держалось. На трёх — нет, и это ровно тот дефект-класс, который уже
дал расхождения в ценах (B5), названиях тарифов (B7), правиле этапа (A13) и
адресе отчёта (E6): копия правила в двух местах молча разъезжается.

Здесь — единственный источник правды об аудитории. Всё остальное спрашивает
у реестра.
"""
from __future__ import annotations

from dataclasses import dataclass
from typing import Optional


@dataclass(frozen=True)
class Audience:
    """Кто пришёл, что ему нужно и как с ним разговаривает платный разбор."""

    key: str
    #: адрес витрины: "" — главная, иначе /{slug}
    slug: str
    #: как аудитория называется в воронке владельца
    label: str
    #: кто читает результат — от этого зависит вся оптика разбора
    reader: str
    #: системная роль для модели
    persona: str
    #: что означает балл жизнеспособности именно для этого читателя
    viability: str
    #: обязана ли смета быть посчитана до копейки (комиссия спросит)
    estimate_required: bool = False
    #: как человек говорит про себя сам — этим подписан переключатель витрин.
    #: Наши внутренние ключи («business») человеку ничего не говорят (принцип 5).
    switch_label: str = ""


BUSINESS = Audience(
    key="business",
    slug="",
    label="фаундеры",
    reader="сам фаундер: решает, вкладывать ли в идею время и деньги",
    persona="""Ты — жёсткий аналитик венчурного фонда. Зарабатываешь тем, что
находишь структурные проблемы в идеях ДО того, как в них вложат время и
деньги — а не тем, что хвалишь идеи.""",
    viability="""честная оценка жизнеспособности идеи В
   ТЕКУЩЕМ виде, не оптимистичная скидка. 85+ — редкость, такой балл отдельно
   обоснуй в viability_summary.""",
    switch_label="Проверяю идею для своего дела",
)


SOCIAL_CONTRACT = Audience(
    key="social_contract",
    slug="social-contract",
    label="соцконтракт",
    reader="комиссия соцзащиты: решает, выдать ли выплату на своё дело",
    persona="""Ты — экономист, который готовит обоснование бизнес-плана для комиссии
по социальному контракту. Заявитель — обычный человек, часто самозанятый
или безработный, который просит у государства единовременную выплату
(до ~350 000 ₽) на своё дело. Комиссия отказывает не из-за «недостаточной
амбициозности», а из-за необоснованных сумм в смете, нереалистичной выручки
и непонимания, на что конкретно уйдут деньги.
Венчурные критерии здесь НЕ применяй: масштабируемость, кратный рост, выход
на другие рынки — неуместны и вредны. Устойчивый доход одного человека или
семьи — это нормальная и достаточная цель. Но честность сохраняй: если дело
в текущем виде не прокормит заявителя или смета не сойдётся — скажи прямо,
лучше узнать это до комиссии, чем получить отказ.""",
    viability="""насколько дело реально прокормит
   заявителя и насколько смета выдержит вопросы комиссии. Оценивай не
   амбициозность, а реалистичность: сходится ли экономика, хватит ли выплаты
   на старт, есть ли платящие клиенты рядом. Крепкое локальное дело без роста
   — это высокий балл, а не низкий.""",
    estimate_required=True,
    switch_label="Готовлю обоснование для соцзащиты",
)


AUDIENCES: dict[str, Audience] = {a.key: a for a in (BUSINESS, SOCIAL_CONTRACT)}

#: Аудитория по умолчанию. Мусор в `purpose` не должен ронять страницу, но и
#: притворяться соцконтрактом тоже не должен: подсунуть комиссионную оптику
#: тому, кто её не просил, хуже, чем показать обычную (принцип 7).
DEFAULT = BUSINESS


def get(key: Optional[str]) -> Audience:
    return AUDIENCES.get(key or "", DEFAULT)


def keys() -> tuple[str, ...]:
    return tuple(AUDIENCES)


def by_slug(slug: str) -> Audience:
    slug = (slug or "").strip("/")
    for a in AUDIENCES.values():
        if a.slug == slug:
            return a
    return DEFAULT


def labels() -> dict[str, str]:
    """Русские названия для панели владельца — сервер, а не копия в скрипте."""
    return {a.key: a.label for a in AUDIENCES.values()}
