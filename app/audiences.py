AUDIENCES: dict[str, Audience] = {a.key: a for a in (BUSINESS, SOCIAL_CONTRACT, STUDENT)}

#: Аудитория по умолчанию. Мусор в `purpose` не должен ронять страницу, но и
#: притворяться соцконтрактом тоже не должен: подсунуть комиссионную оптику
#: тому, кто её не просил, хуже, чем показать обычную (принцип 7).
DEFAULT = BUSINESS


def get(key: Optional[str]) -> Audience:
    return AUDIENCES.get(key or "", DEFAULT)


def keys() -> tuple[str, ...]:
    return tuple(AUDIENCES)


def by_slug(slug: str) -> Audience:
    slug = (slug or "").strip("/")
    for a in AUDIENCES.values():
        if a.slug == slug:
            return a
    return DEFAULT


def for_page(key: Optional[str]) -> dict:
    """Что нужно знать странице результата, чтобы говорить со своей аудиторией.

    Раньше в скрипте стояла ветка `IS_SOCIAL_CONTRACT` — то есть «аудиторий
    ровно две». Отдаём данными: адрес своей витрины, что показывать главным
    действием и что говорить при слабом спросе.
    """
    a = get(key)
    return {"key": a.key, "home": f"/{a.slug}" if a.slug else "/",
            "plan_first": a.plan_first, "weak_demand": a.weak_demand}


def labels() -> dict[str, str]:
    """Русские названия для панели владельца — сервер, а не копия в скрипте."""
    return {a.key: a.label for a in AUDIENCES.values()}
