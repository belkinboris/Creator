#: `scores[].note` и `overall` пишет LLM на бесплатной проверке (score_idea) —
#: это короткие подписи к баллам, а не данные Яндекса.
_OPINION_KEYS = ("scores", "overall")


def _user_message(idea: str, demand_data: dict, chosen_offer: dict | None = None) -> str:
    """Контекст для модели, разделённый на измеренное и оценочное.

    Живой прогон 2026-08-04 показал, зачем: подпись к шкале конкуренции
    (её пишет LLM на бесплатной проверке) содержала выдуманное «162
    стационарные точки». Раньше весь demand_data уезжал в отчёт одним
    ключом «данные_проверки_спроса», и модель отчёта честно приняла чужую
    выдумку за измерение — число 162 разошлось по ШЕСТИ разделам платного
    бизнес-плана как факт: «наличие 162 фиксированных точек во Владимире»,
    «на Яндекс Услугах представлено более 162 сервисов». Мы такого не
    измеряли никогда: у нас есть частотности Вордстата и домены из выдачи,
    и всё. Для документа, который несут в комиссию соцзащиты, выдуманное
    число особенно дорого стоит.
    """
    idea = (idea or "").strip()[:MAX_IDEA_CHARS]
    if len(idea) < 10:
        raise ReportEngineError("Идея слишком короткая для разбора.")
    demand_data = demand_data or {}
    measured = {k: v for k, v in demand_data.items() if k not in _OPINION_KEYS}
    opinion = {k: v for k, v in demand_data.items() if k in _OPINION_KEYS}
    context = {
        "идея": idea,
        # Только это — настоящие цифры: частотности Вордстата и выдача Яндекса.
        "измеренные_данные": measured,
        # А это — оценка модели на бесплатном шаге. Ссылаться на неё как на
        # факт нельзя, брать оттуда числа — тем более.
        "оценка_на_бесплатном_шаге_это_мнение_а_не_измерение": opinion,
    }
    if chosen_offer:
        context["выбранное_позиционирование"] = chosen_offer
    return json.dumps(context, ensure_ascii=False)


async def _call_llm(system: str, user: str, max_tokens: int, *, _post=None) -> str:
    return await llm_adapter.call(system, user, max_tokens,
                                  model=SOZDATEL_REPORT_MODEL, _post=_post)


def _parse(text: str) -> dict:
    cleaned = (text or "").strip()
    if cleaned.startswith("```"):
        cleaned = cleaned.split("```")[1] if "```" in cleaned[3:] else cleaned[3:]
        cleaned = cleaned.removeprefix("json").strip()
    start, end = cleaned.find("{"), cleaned.rfind("}")
    if start == -1 or end == -1:
        raise ReportEngineError("Не удалось разобрать ответ модели.")
    return json.loads(cleaned[start:end + 1])


async def generate_core(idea: str, demand_data: dict, tier: str = "full",
                        chosen_offer: dict | None = None,
                        purpose: str = PURPOSE_BUSINESS,
                        *, _post=None, _attempt: int = 1) -> dict:
    """Балл, объяснение и названные риски. Быстрый вызов — показывается первым,
    пока секции ещё собираются."""
    user_msg = _user_message(idea, demand_data, chosen_offer)
    try:
        text = await _call_llm(_core_prompt(tier, purpose), user_msg,
                               MAX_TOKENS_CORE, _post=_post)
        data = _parse(text)
    except (json.JSONDecodeError, ReportEngineError):
        if _attempt == 1:
            return await generate_core(idea, demand_data, tier, chosen_offer, purpose,
                                       _post=_post, _attempt=2)
        raise ReportEngineError("Модель вернула неразборчивый ответ. Попробуйте ещё раз.")
    except (httpx.HTTPError, httpx.TimeoutException, llm_adapter.LLMAdapterError) as e:
        if _attempt == 1:
            return await generate_core(idea, demand_data, tier, chosen_offer, purpose,
                                       _post=_post, _attempt=2)
        raise ReportEngineError(f"Сервис анализа недоступен: {e}")

    score = data.get("viability_score")
    if not isinstance(score, (int, float)) or not (1 <= score <= 100):
        raise ReportEngineError(_MALFORMED, tech="нет корректного viability_score")
    # A16 (PRODUCT_ROADMAP): без этого viability_score — независимая оценка
    # модели, которая ничего не знает про потолок "спрос это ворота" из
    # check_demand -- на экране рядом оказывались два несогласованных числа
    # по одной идее (напр. "4/10" и "65/100"), без единого слова, почему они
    # расходятся. Владелец решил: не жёсткий min-потолок (для соцконтракта
    # устойчивое локальное дело без роста законно получает высокий балл — тот
    # же A16), а медиана модельной оценки и всех 4 шкал бесплатной проверки
    # (спрос, конкуренция, своевременность, реализуемость, приведённых к
    # шкале 0-100) -- сглаживает расхождение, но не даёт независимой оценке
    # оторваться от того, что реально измерено.
    component_values = [s.get("value") for s in (demand_data.get("scores") or [])
                        if isinstance(s.get("value"), (int, float))]
    if component_values:
        score = round(statistics.median([v * 10 for v in component_values] + [score]))
    summary = str(data.get("viability_summary") or "").strip()
    if not summary:
        raise ReportEngineError(_MALFORMED, tech="нет viability_summary")

    expected = _risk_count(tier)
    raw = data.get("top_risks")
    if not isinstance(raw, list) or len(raw) < expected:
        raise ReportEngineError(_MALFORMED, tech="недостаточно top_risks")
    risks = []
    for r in raw[:expected]:
        title = str((r or {}).get("title") or "").strip()
        body = str((r or {}).get("body") or "").strip()
        if not title or not body:
            raise ReportEngineError(_MALFORMED, tech="риск без title/body")
        risks.append({"title": title, "body": body})

    return {"viability_score": int(score), "viability_summary": summary,
            "viability_label": _viability_label(int(score)), "top_risks": risks}


def _viability_label(score: int) -> str:
    """Короткая словесная метка рядом с баллом — так же, как у dimeadozen.ai
    ("Strong execution path", владелец прислал референс 2026-08-02). Балл сам
    по себе плохо читается без контекста ("62 из 100 — это много или мало?"),
    а метка объясняет за секунду. Детерминированная функция, не LLM — тот же
    принцип, что и у compute_verdict в demand.py: вердикт не должен зависеть
    от того, как модель сформулирует его в этот раз."""
    if score >= 80:
        return "Сильная позиция для запуска"
    if score >= 60:
        return "Рабочий вариант, есть слабые места"
    if score >= 40:
        return "Нужна доработка перед запуском"
    return "Рискованно запускать в текущем виде"


async def generate_section(key: str, idea: str, demand_data: dict, tier: str = "full",
                           chosen_offer: dict | None = None,
                           purpose: str = PURPOSE_BUSINESS,
                           viability_score: int | None = None,
                           *, _post=None, _attempt: int = 1) -> dict:
    """Один раздел — один вызов модели со своим ТЗ и своим бюджетом токенов.

    `viability_score` нужен только разделу «Вердикт» — см. `_verdict_anchor`.
    Балл к этому моменту уже посчитан (`generate_core` идёт первым и лежит
    в `report_json`), так что раздел не пересчитывает его заново."""
    if key not in section_keys(tier):
        raise ReportEngineError(f"секции {key} нет в тарифе {tier}")
    user_msg = _user_message(idea, demand_data, chosen_offer)
    try:
        text = await _call_llm(_section_prompt(key, tier, purpose, viability_score),
                               user_msg, MAX_TOKENS_SECTION, _post=_post)
        data = _parse(text)
    except (json.JSONDecodeError, ReportEngineError):
        if _attempt == 1:
            return await generate_section(key, idea, demand_data, tier, chosen_offer,
                                          purpose, viability_score,
                                          _post=_post, _attempt=2)
        raise ReportEngineError("Модель вернула неразборчивый ответ. Попробуйте ещё раз.")
    except (httpx.HTTPError, httpx.TimeoutException, llm_adapter.LLMAdapterError) as e:
        if _attempt == 1:
            return await generate_section(key, idea, demand_data, tier, chosen_offer,
                                          purpose, viability_score,
                                          _post=_post, _attempt=2)
        raise ReportEngineError(f"Сервис анализа недоступен: {e}")

    body = str(data.get("body") or "").strip()
    if not body:
        raise ReportEngineError(_MALFORMED, tech=f"пустой раздел {key}")
    # Промпт финансового раздела прямо запрещает модели отказаться считать
    # («недостаточно данных»), но до сих пор это была просьба без проверки:
    # непустой ответ без единой суммы проходил как валидный. Для аудитории,
    # где смета — единственное, за чем платят (комиссии соцзащиты она нужна
    # «до копейки», Audience.estimate_required), непосчитанная смета — это не
    # раздел похуже, а недоставленная услуга (принцип 3).
    if (key == "finance" and audiences.get(purpose).estimate_required
            and "₽" not in body and "руб" not in body.lower()):
        raise ReportEngineError(_MALFORMED, tech=f"раздел {key}: нет сумм в рублях")

    result = {"key": key, "title": section_title(key, purpose), "body": body}
    if _spec(key, purpose).get("wants_table"):
        table = _parse_table(data.get("table"))
        if table:
            result["table"] = table
        elif audiences.get(purpose).estimate_required:
            # Соцзащита читает смету построчно (F: соц-план.рф, 2026-08-02) —
            # для этой аудитории таблица не украшение, а часть услуги, за
            # которую заплатили, как и суммы в body чуть выше.
            raise ReportEngineError(_MALFORMED, tech=f"раздел {key}: нет таблицы сметы")
    return result


def _parse_table(raw: object) -> dict | None:
    """Смета построчно, не абзацем -- см. wants_table в SECTION_SPECS.
    Мягко деградирует до None при любой кривизне: таблица — дополнение к
    body, а не замена, отчёт не должен падать из-за одной лишней строки."""
    if not isinstance(raw, dict):
        return None
    rows_raw = raw.get("rows")
    if not isinstance(rows_raw, list):
        return None
    rows = []
    for row in rows_raw:
        if not isinstance(row, dict):
            continue
        item = str(row.get("item") or "").strip()
        amount = row.get("sum")
        if item and isinstance(amount, (int, float)) and not isinstance(amount, bool):
            rows.append({"item": item, "sum": amount})
    if not rows:
        return None
    total = raw.get("total")
    if not isinstance(total, (int, float)) or isinstance(total, bool):
        total = sum(r["sum"] for r in rows)
    caption = str(raw.get("caption") or "").strip() or "Смета"
    return {"caption": caption, "rows": rows, "total": total}


async def generate_report(idea: str, demand_data: dict, tier: str = "quick",
                          chosen_offer: dict | None = None,
                          purpose: str = PURPOSE_BUSINESS, *, _post=None) -> dict:
    """Собрать отчёт целиком. Оставлено для прямых вызовов и тестов; страница
    отчёта наполняет разделы по одному (см. /api/report/{id}/section), чтобы
    человек не ждал все разделы разом перед пустым экраном."""
    core = await generate_core(idea, demand_data, tier, chosen_offer, purpose, _post=_post)
    sections = []
    for key in section_keys(tier):
        sections.append(await generate_section(key, idea, demand_data, tier,
                                               chosen_offer, purpose,
                                               core.get("viability_score"), _post=_post))
    return {**core, "sections": sections}
