def section_keys(tier: str) -> list[str]:
    return list(QUICK_KEYS) if tier == "quick" else [s["key"] for s in SECTION_SPECS]


def _spec(key: str, purpose: str) -> dict:
    for s in SECTION_SPECS:
        if s["key"] != key:
            continue
        merged = {k: v for k, v in s.items() if k != "by_audience"}
        merged.update((s.get("by_audience") or {}).get(purpose) or {})
        return merged
    raise ReportEngineError(f"неизвестная секция {key}")


def section_title(key: str, purpose: str = PURPOSE_BUSINESS) -> str:
    return _spec(key, purpose)["title"]


def _risk_count(tier: str) -> int:
    return 2 if tier == "quick" else 4


